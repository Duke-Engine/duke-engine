package uz.duke.client3d;

/** One block of the hero's bar, as {@link PanelLook#blocks} lists them. */
public enum PanelBlock {
    /** The minimap's socket, with the column of order buttons beside it. */
    MINIMAP,
    /** His portrait with what is left of him under it, and beside it his name, experience and figures. */
    HERO,
    /** What he carries. */
    BAG,
    /** What he can cast. */
    SKILLS,
    /** How deep he is. */
    DEPTH
}
